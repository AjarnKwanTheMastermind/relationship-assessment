export type Band = "critical" | "warning" | "safe";
export type CategoryStatus = "red" | "warning" | "healthy";

export type CategoryResult = {
  num: 1 | 2 | 3;
  title: string;
  score: number;
  maxScore: number;
  status: CategoryStatus;
  desc: string;
  action: string;
};

